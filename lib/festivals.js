/**
 * Returns today's date formatted as YYYY-MM-DD in Asia/Kolkata timezone.
 * Uses Intl.DateTimeFormat so it reliably resolves Indian standard date
 * regardless of client device timezone.
 */
export function getKolkataDateString(date = new Date()) {
  try {
    const formatter = new Intl.DateTimeFormat('en-CA', {
      timeZone: 'Asia/Kolkata',
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
    });
    return formatter.format(date);
  } catch {
    // Fallback if Intl fails
    const utc = date.getTime() + date.getTimezoneOffset() * 60000;
    const istOffset = 5.5 * 3600000;
    const istDate = new Date(utc + istOffset);
    return istDate.toISOString().slice(0, 10);
  }
}

/**
 * Finds festival matching today's date in IST.
 * If overrideDate is provided (e.g. for testing), matches against that.
 */
export function getTodayFestival(overrideDate = null) {
  const targetDate = overrideDate || getKolkataDateString();
  return FESTIVALS.find((f) => f.date === targetDate) || null;
}

/**
 * Find festival by keyword/ID (useful for dev preview e.g. ?festival=diwali)
 */
export function getFestivalByKeyword(keyword) {
  if (!keyword || typeof keyword !== 'string') return null;
  const term = keyword.trim().toLowerCase();
  return (
    FESTIVALS.find(
      (f) =>
        f.id.toLowerCase().includes(term) ||
        f.name.toLowerCase().includes(term) ||
        f.greeting.toLowerCase().includes(term)
    ) || null
  );
}
